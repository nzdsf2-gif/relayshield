#!/usr/bin/env python3
"""Keep CLAUDE.md small enough to be read, without losing a word of the history.

WHY THIS EXISTS. CLAUDE.md reached 802,620 characters across 212 sections because every
session appended a dated record to it. Andrew reported that his local Claude Code reads
only up to 150,000 characters, so most of the file, including the rules written
for him, was never seen. (The 150,000 figure is his report; it was not verified against
Claude Code's own documentation.) A size limit stated in prose does not hold, because the
cheapest thing a session can do is append, so the limit is enforced here and in
test_claude_md_size.py.

LAYOUT (all of it verbatim; nothing was reworded when the file was split):

    CLAUDE.md                          standing rules only. Hard cap CLAUDE_MD_CAP.
    docs/claude_memory/LOG_CURRENT.md  recent session records. NEW RECORDS GO HERE.
    docs/claude_memory/archive_NN.md   older records, in original order. Not auto-loaded.
    docs/claude_memory/INDEX.md        every heading in all of the above, with file:line.

    python3 tools/claude_memory.py --check            sizes + index freshness (exit 1 on a problem)
    python3 tools/claude_memory.py --index --write    regenerate INDEX.md
    python3 tools/claude_memory.py --rotate           dry run: what would move out of LOG_CURRENT.md
    python3 tools/claude_memory.py --rotate --write   move the oldest LOG_CURRENT sections into the
                                                      newest archive volume (or a new one), then reindex

Sections are split on lines that begin with "## " and nothing else. A fence-aware parser
was tried and rejected: CLAUDE.md has unbalanced code fences in older sections, which makes
every later "## " look like it is inside a fence. A "### " heading never splits.
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MEM = os.path.join(ROOT, "docs", "claude_memory")
CLAUDE_MD = os.path.join(ROOT, "CLAUDE.md")
LOG = os.path.join(MEM, "LOG_CURRENT.md")
INDEX = os.path.join(MEM, "INDEX.md")

CLAUDE_MD_CAP = 120_000     # below the 150,000 Andrew reported, with room for one more session
LOG_CAP = 90_000            # LOG_CURRENT.md; --rotate brings it back to LOG_TARGET
LOG_TARGET = 60_000
VOLUME_CAP = 90_000         # an archive volume stays readable in one Read call

ARCHIVE_HEADER = ("<!-- Verbatim sections moved out of CLAUDE.md on 2026-10-18, original order. Not auto-loaded.\n"
                  "     Find one with: grep -n 'WORDS' docs/claude_memory/INDEX.md -->\n\n")
LOG_HEADER = ("# LOG_CURRENT: recent session records\n\n"
              "<!-- NEW SESSION RECORDS ARE APPENDED HERE, NEVER TO CLAUDE.md. Newest last. The last\n"
              "     'WHERE ... LEFT THINGS' section supersedes the ones above it. When this passes\n"
              "     90,000 characters run: python3 tools/claude_memory.py --rotate --write -->\n\n")


def split_sections(text):
    """(preamble, [(heading, body)]). body starts at its '## ' line; joined with '\\n' it round-trips."""
    lines = text.split("\n")
    starts = [i for i, ln in enumerate(lines) if ln.startswith("## ")]
    if not starts:
        return text, []
    pre = "\n".join(lines[:starts[0]])
    out = []
    for k, s in enumerate(starts):
        e = starts[k + 1] if k + 1 < len(starts) else len(lines)
        out.append((lines[s][3:], "\n".join(lines[s:e])))
    return pre, out


def join_sections(pre, secs):
    return pre + ("\n" if pre and secs else "") + "\n".join(b for _, b in secs)


def read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def write(path, text):
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def volumes(mem=None):
    mem = mem or MEM
    return sorted(f for f in os.listdir(mem) if f.startswith("archive_") and f.endswith(".md"))


def build_index(root=None):
    root = root or ROOT
    mem = os.path.join(root, "docs", "claude_memory")
    files = [("CLAUDE.md", os.path.join(root, "CLAUDE.md")), ("LOG_CURRENT.md", os.path.join(mem, "LOG_CURRENT.md"))]
    files += [(v, os.path.join(mem, v)) for v in volumes(mem)]
    rows = []
    for name, path in files:
        if not os.path.exists(path):
            continue
        for n, line in enumerate(read(path).split("\n"), 1):
            if line.startswith("## "):
                rows.append("%s:%d  %s" % (name, n, line[3:].strip()[:140]))
    head = ("# INDEX of every '## ' section in CLAUDE.md and docs/claude_memory\n"
            "# GENERATED by tools/claude_memory.py --index --write. Do not edit by hand.\n"
            "# file:line  heading\n\n")
    return head + "\n".join(rows) + "\n"


def check(root=None):
    root = root or ROOT
    mem = os.path.join(root, "docs", "claude_memory")
    problems = []
    sizes = {"CLAUDE.md": (os.path.join(root, "CLAUDE.md"), CLAUDE_MD_CAP),
             "LOG_CURRENT.md": (os.path.join(mem, "LOG_CURRENT.md"), LOG_CAP)}
    for v in volumes(mem):
        sizes[v] = (os.path.join(mem, v), VOLUME_CAP + 5_000)   # a volume may end one section past the cap
    for name, (path, cap) in sizes.items():
        if not os.path.exists(path):
            problems.append("%s is missing" % name)
        elif len(read(path)) > cap:
            problems.append("%s is %d characters, over its cap of %d" % (name, len(read(path)), cap))
    idx = os.path.join(mem, "INDEX.md")
    if not os.path.exists(idx) or read(idx) != build_index(root):
        problems.append("INDEX.md is missing or stale: run --index --write")
    return problems


def rotate(root=None, do_write=False):
    """Move the oldest LOG_CURRENT.md sections out until it is under LOG_TARGET. Returns the headings moved."""
    root = root or ROOT
    mem = os.path.join(root, "docs", "claude_memory")
    log_path = os.path.join(mem, "LOG_CURRENT.md")
    pre, secs = split_sections(read(log_path))
    moved = []
    # Always keep the newest section: a log that rotates itself empty hides the current state.
    while len(join_sections(pre, secs)) > LOG_TARGET and len(secs) > 1:
        moved.append(secs.pop(0))
    if not moved or not do_write:
        return [h for h, _ in moved]
    vols = volumes(mem)
    last = os.path.join(mem, vols[-1]) if vols else None
    for heading, body in moved:
        if last is None or len(read(last)) + len(body) + 1 > VOLUME_CAP:
            last = os.path.join(mem, "archive_%02d.md" % (len(volumes(mem)) + 1))
            write(last, ARCHIVE_HEADER)
        cur = read(last)
        write(last, cur + ("" if cur.endswith("\n") else "\n") + body + "\n")
    write(log_path, join_sections(pre, secs))
    write(os.path.join(mem, "INDEX.md"), build_index(root))
    return [h for h, _ in moved]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--index", action="store_true")
    ap.add_argument("--rotate", action="store_true")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    if a.index:
        text = build_index()
        if a.write:
            write(INDEX, text)
            print("wrote %s (%d chars)" % (INDEX, len(text)))
        else:
            print("dry run: INDEX.md would be %d chars; --write to save" % len(text))
        return 0
    if a.rotate:
        moved = rotate(do_write=a.write)
        for h in moved:
            print(("moved   " if a.write else "would move  ") + h[:110])
        if not moved:
            print("LOG_CURRENT.md is under its target; nothing to move")
        return 0
    problems = check()
    for p in problems:
        print("PROBLEM:", p)
    if not problems:
        print("OK: CLAUDE.md %d chars (cap %d), LOG_CURRENT.md %d chars (cap %d), index current"
              % (len(read(CLAUDE_MD)), CLAUDE_MD_CAP, len(read(LOG)), LOG_CAP))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
