#!/usr/bin/env python3
"""Regenerate mcp_proxy/taxonomy.py from the approved taxonomy JSON.

    python3 tools/gen_proxy_taxonomy.py            # rewrite the module
    python3 tools/gen_proxy_taxonomy.py --check    # exit 1 if it is stale

The proxy is zero-dependency and ships on its own, so it cannot read DynamoDB or
the JSON at run time. It carries a SNAPSHOT of the fields a verdict needs
(attack pattern, mitigation, disclosure). test_mcp_discovery.py runs --check, so
the snapshot cannot drift from the source of truth.
"""
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "intel_taxonomy" / "mcp_attack_patterns_2026-10-10.json"
OUT = REPO / "mcp_proxy" / "taxonomy.py"
KEEP = ("disclosure", "fit", "poison_category", "attack_pattern", "mitigation")


def render() -> str:
    doc = json.loads(SRC.read_text())
    entries = {e["id"]: {k: e[k] for k in KEEP} for e in doc["entries"]}
    body = json.dumps(entries, indent=4, sort_keys=True, ensure_ascii=False)
    return (
        '"""GENERATED by tools/gen_proxy_taxonomy.py. DO NOT EDIT BY HAND.\n\n'
        "Snapshot of the approved MCP attack-pattern taxonomy\n"
        f"(version {doc['version']}, approved by {doc['approved_by']} "
        f"on {doc['approved_date']}).\n"
        "The source of truth is intel_taxonomy/mcp_attack_patterns_*.json and the\n"
        'relayshield_mcp_taxonomy table. Regenerate, never edit.\n"""\n\n'
        f"TAXONOMY_VERSION = {doc['version']!r}\n\n"
        f"ENTRIES = {body}\n"
    )


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("STALE: run python3 tools/gen_proxy_taxonomy.py", file=sys.stderr)
            return 1
        print("up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
